"""Is the R0 demand identical to the qualification demand? (condition for reusing C19 and C25 on R0; read only)

    python tools/comparators/check_r0_demand.py --out logs\\check_r0_demand.json

Compares, without simulation:
  1. specification: per-stream counts, routes, stream ranks, generation window, cut-off, total N, and the absence
     of any time profile in R0 (homogeneous intensity);
  2. law of the generator: frozen adaptive_qmix.traffic draws each departure i.i.d. uniform on the integer
     seconds [0, 3600) (Generator.integers); the robustness generator draws Generator.choice over the same seconds
     with the profile weights, all equal for R0. Checked here: the R0 weights are constant;
  3. files: the vType and route elements written for R0 and for the qualification are identical, the vehicle
     attributes other than id and depart are identical, and both are sorted by (depart, stream rank, rank in
     stream);
  4. empirical (informative): departures pooled over 5 R0 manifests (unused R0 design seeds 8011-8015) versus 5
     qualification design manifests (2001-2005, regenerated by the frozen generator, deterministic): two-sample
     Kolmogorov-Smirnov distance per stream.
Expected differences that are NOT demand differences, reported as such: vehicle identifiers, the traffic
seeds and the SUMO seeds (new family, by construction). Verdict IDENTICAL_LAW only if 1-3 hold; else DIFFERS,
with the list (exit code 1).
"""
from __future__ import absolute_import, print_function

import argparse
import json
import math
import os
import shutil
import sys
import tempfile
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "robustness"))
PROTECTED = os.environ.get("QMIX_PROTECTED_ROOT", r"C:\Users\LENOVO\QMIX_PROTECTED")
sys.path.insert(0, os.path.join(PROTECTED, "src"))

import scenario_traffic as st  # noqa: E402

R0 = "R0_reference"
R0_SEEDS = (8011, 8012, 8013, 8014, 8015)
QUALIFICATION_SEEDS = (2001, 2002, 2003, 2004, 2005)


def ks_distance(a, b):
    a, b = sorted(a), sorted(b)
    i = j = 0
    d = 0.0
    while i < len(a) and j < len(b):
        x = min(a[i], b[j])
        while i < len(a) and a[i] == x:
            i += 1
        while j < len(b) and b[j] == x:
            j += 1
        d = max(d, abs(i / float(len(a)) - j / float(len(b))))
    return d


def ks_pvalue(d, n, m):
    """Asymptotic two-sample KS p-value (Kolmogorov distribution)."""
    en = math.sqrt(n * m / float(n + m))
    lam = (en + 0.12 + 0.11 / en) * d
    total = 0.0
    for k in range(1, 101):
        total += 2 * (-1) ** (k - 1) * math.exp(-2 * k * k * lam * lam)
    return max(0.0, min(1.0, total))


def route_file(path):
    root = ET.parse(path).getroot()
    vtype = [dict(e.attrib) for e in root.findall("vType")]
    routes = [dict(e.attrib) for e in root.findall("route")]
    vehicles = [dict(e.attrib) for e in root.findall("vehicle")]
    return vtype, routes, vehicles


def check(config):
    from adaptive_qmix import traffic as T
    spec = st.load_spec()
    sc = spec["scenarios"][R0]
    demand = config["demand"]
    problems, notes = [], []
    q_streams = demand["streams"]
    for name, q in q_streams.items():
        r = sc["streams"].get(name)
        if r is None:
            problems.append("stream {} absent from R0".format(name))
            continue
        if int(r["count"]) != int(q["count"]):
            problems.append("stream {}: count {} in R0, {} in the qualification".format(name, r["count"], q["count"]))
        if list(spec["routes"][name]) != list(q["route"]):
            problems.append("stream {}: route differs".format(name))
        if int(spec["stream_rank"][name]) != int(q["rank"]):
            problems.append("stream {}: rank differs".format(name))
        if "profile" in r:
            problems.append("stream {}: R0 has a time profile".format(name))
        w = st.profile_weights(r, int(spec["generation_end_s"]))
        if w.min() != w.max():
            problems.append("stream {}: R0 weights are not constant".format(name))
    if set(sc["streams"]) != set(q_streams):
        problems.append("stream sets differ")
    for key in ("generation_end_s", "maximum_simulation_s"):
        if int(spec[key]) != int(demand[key]):
            problems.append("{} differs: {} vs {}".format(key, spec[key], demand[key]))
    total = sum(int(s["count"]) for s in sc["streams"].values())
    if total != int(demand["scheduled_total"]):
        problems.append("N differs: {} vs {}".format(total, demand["scheduled_total"]))
    if demand.get("model") != "conditioned_discrete_time_homogeneous_multinomial":
        problems.append("unexpected frozen demand model {}".format(demand.get("model")))

    work = tempfile.mkdtemp()
    try:
        r0, qual = {}, {}
        for seed in R0_SEEDS:
            prefix = os.path.join(work, "r0_{}".format(seed))
            st.write(spec, R0, seed, st.generate(spec, R0, seed), prefix, demand["vehicle_type"])
            r0[seed] = prefix
        for seed in QUALIFICATION_SEEDS:
            prefix = os.path.join(work, "q_{}".format(seed))
            T.write_manifest(T.generate_manifest_records(config, "benchmark_design", seed), config, prefix,
                             "benchmark_design", seed)
            qual[seed] = prefix
        rv, rr, rveh = route_file(r0[R0_SEEDS[0]] + ".rou.xml")
        qv, qr, qveh = route_file(qual[QUALIFICATION_SEEDS[0]] + ".rou.xml")
        if rv != qv:
            problems.append("vType differs: {} vs {}".format(rv, qv))
        if rr != qr:
            problems.append("route elements differ")
        strip = lambda v: dict((k, x) for k, x in v.items() if k not in ("id", "depart", "route"))  # noqa: E731
        if set(json.dumps(strip(v), sort_keys=True) for v in rveh) != set(json.dumps(strip(v), sort_keys=True) for v in qveh):
            problems.append("vehicle attributes differ")
        empirical = {}
        for name in sorted(q_streams, key=lambda n: q_streams[n]["rank"]):
            a = [float(v["depart"]) for p in r0.values() for v in route_file(p + ".rou.xml")[2]
                 if v["route"] == "route_" + name]
            b = [float(v["depart"]) for p in qual.values() for v in route_file(p + ".rou.xml")[2]
                 if v["route"] == "route_" + name]
            d = ks_distance(a, b)
            empirical[name] = {"r0_departures": len(a), "qualification_departures": len(b), "ks_distance": d,
                               "ks_pvalue_asymptotic": ks_pvalue(d, len(a), len(b)),
                               "mean_depart_r0": sum(a) / len(a), "mean_depart_qualification": sum(b) / len(b)}
        for prefix in list(r0.values()) + list(qual.values()):
            veh = route_file(prefix + ".rou.xml")[2]
            ranks = dict((n, int(q_streams[n]["rank"])) for n in q_streams)
            keys = [(float(v["depart"]), ranks[v["route"][len("route_"):]]) for v in veh]
            if keys != sorted(keys):
                problems.append("{}: vehicles not sorted by (depart, stream rank)".format(os.path.basename(prefix)))
        notes += ["vehicle identifiers differ (robustness_0_s<seed>_... vs benchmark_design_m000_...): naming only",
                  "traffic and SUMO seeds differ by construction (robustness family code 80): new realisations of "
                  "the same law",
                  "realised draws differ (Generator.choice with equal weights vs Generator.integers): same law, "
                  "i.i.d. uniform on the integer seconds [0, 3600)"]
    finally:
        shutil.rmtree(work)
    return {"verdict": "IDENTICAL_LAW" if not problems else "DIFFERS", "problems": problems, "notes": notes,
            "empirical_informative": empirical, "r0_seeds": list(R0_SEEDS),
            "qualification_seeds_regenerated": list(QUALIFICATION_SEEDS),
            "scenario_spec_sha256": spec["_sha256"]}


def main(argv=None):
    from adaptive_qmix.config import load_config
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    config = load_config(os.path.join(PROTECTED, "config", "adaptive_qmix", "qualification_300m_medium.json"))
    result = check(config)
    text = json.dumps(result, indent=1)
    if a.out:
        with open(a.out, "w") as f:
            f.write(text + "\n")
    print(text)
    return 0 if result["verdict"] == "IDENTICAL_LAW" else 1


if __name__ == "__main__":
    sys.exit(main())
