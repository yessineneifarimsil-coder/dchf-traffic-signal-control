def check_selections_complete(selections):
    """B1/B2 need every sealed selection of A and A-ext: no primary is chosen from an incomplete set."""
    for profile, labels in REQUIRED_SELECTIONS.items():
        have = sorted(s["label"] for s in selections if s["profile"] == profile)
        if have != sorted(labels):
            raise BError("{}: sealed selections {} but {} are required (A finished, A-ext finalised?)".format(
                profile, have, sorted(labels)))
    other = [s for s in selections if s["profile"] not in REQUIRED_SELECTIONS]
    if other:
        raise BError("unexpected selections {}".format([s["file"] for s in other]))


def choose_primary(selections, profile):
    """B1: lowest validation J among the sealed selections of the profile (ties: LABEL_ORDER); R0, R4: C19."""
    if profile not in SEARCHED:
        return {"label": C19_LABEL, "validation_J": C19_VALIDATION_J, "rule": "frozen C19 8/5 D9 (no search)"}
    mine = [s for s in selections if s["profile"] == profile]
    if not mine:
        raise BError("no sealed selection for {}".format(profile))
    best = sorted(mine, key=lambda s: (s["validation_J"], LABEL_ORDER.index(s["label"])))[0]
    return {"label": best["label"], "validation_J": best["validation_J"], "rule": "lowest validation J (B1)",
            "candidates": dict((s["label"], s["validation_J"]) for s in mine)}


def margin(j_val, plan=None):
    rule = (plan or conf_plan())["statistics"]["equivalence_margin"]
    return max(rule["relative"] * float(j_val), rule["floor_s"])


