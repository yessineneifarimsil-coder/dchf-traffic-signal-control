def environment():
    """Python and SUMO versions of the machine running the run-in (recorded; the freeze requires 3.7 / 1.25)."""
    sumo, candidates = None, ["sumo"]
    if os.environ.get("SUMO_HOME"):
        candidates.append(os.path.join(os.environ["SUMO_HOME"], "bin", "sumo"))
    for exe in candidates:
        try:
            text = subprocess.run([exe, "--version"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                  timeout=60).stdout.decode("utf-8", "replace")
            sumo = next((line.strip() for line in text.splitlines() if line.strip()), "")[:120]
            break
        except (OSError, subprocess.SubprocessError) as error:
            sumo = "unknown ({!r})".format(error)
    return {"python": platform.python_version(), "sumo": sumo, "platform": platform.platform()}


def measure_jobs(models, comps):
    """16 runs on DESIGN seeds only, covering every path of B: QMIX, VDN and IDQN with and without the guarantee,
    the fixed plan (OFT g5, C19), actuated min7, the NEW actuated g5, the time-of-day plan and canonical max pressure;
    counters, signal checks, gzip and the re-read by the real reader are exercised for each."""
    r0, r1, r3 = "R0_reference", "R1_sparse_secondary_heavy_main", "R3_time_varying"
    d0, d1, d3 = SD.seeds(r0, "comparator_design"), SD.seeds(r1, "comparator_design"), SD.seeds(r3, "comparator_design")
    pick = dict((meth, [m for m in models if m["method"] == meth][0]) for meth in (METHODS + (IDQN,)))

    def learned(profile, seed, meth, arm):
        m = pick[meth]
        return {"kind": "learned", "profile": profile, "seed": seed, "model": m["tag"], "method": meth, "arm": arm,
                "controller": "learned:" + arm, "checkpoint_sha256": m["sha256"]}

    def comparator(profile, seed, label):
        spec = comps[profile][label]
        return {"kind": "comparator", "profile": profile, "seed": seed, "spec": spec, "spec_sha256": sha_obj(spec),
                "labels": [label]}
    jobs = [learned(r1, d1[0], "qmix", "guarantee"), learned(r1, d1[0], "vdn", "none"),
            comparator(r1, d1[0], "oft_g5"), comparator(r1, d1[0], "actuated_min7"), comparator(r1, d1[0], "actuated_g5"),
            learned(r1, d1[1], "qmix", "none"), learned(r1, d1[1], "vdn", "guarantee"),
            learned(r3, d3[0], "qmix", "guarantee"), learned(r3, d3[0], "vdn", "none"),
            comparator(r3, d3[0], "tod_g5"), comparator(r3, d3[0], "canonical_mp"),
            learned(r0, d0[0], IDQN, "guarantee"), learned(r0, d0[0], IDQN, "none"), comparator(r0, d0[0], C19_LABEL),
            learned(r0, d0[1], IDQN, "none"), learned(r0, d0[1], "vdn", "guarantee")]
    assert len(jobs) == MEASURE_RUNS
    for k, j in enumerate(jobs):
        j["directory"] = os.path.join("runs", "{:02d}".format(k))
    return jobs


def _measure_one(task):
    """One run-in job, in a worker process: evaluate, finalise as in B, classify, re-read from gzip."""
    work_root, j, prefix, evaluator = task
    final = os.path.join(work_root, j["directory"])
    t0 = time.time()
    out = {"directory": j["directory"], "kind": j["kind"], "method": j.get("method", ""),
           "label": j.get("controller") or j["labels"][0], "profile": j["profile"], "seed": j["seed"],
           "type": ("learned:{}:{}".format(j["method"], j["arm"]) if j["kind"] == "learned"
                    else "comparator:{}".format(j["spec"]["kind"]))}
    try:
        (evaluator or default_evaluator)(work_root, j, prefix, final + ".tmp")
        t_eval = time.time()
        finalize_cell(work_root, j, final + ".tmp", final, int(read_json(prefix + ".metadata.json")["scheduled_total"]))
    except Exception as error:  # noqa: BLE001 - reported to the parent, the run-in fails
        out.update({"wall_s": time.time() - t0, "state": "interrupted", "problems": [repr(error)]})
        return out
    out["wall_s"] = time.time() - t0
    out["evaluation_s"], out["finalize_gzip_s"] = t_eval - t0, time.time() - t_eval
    out["state"], out["problems"] = classify(work_root, j)
    t1 = time.time()
    out["recheck"] = recheck_cell(work_root, j, os.path.join(work_root, "manifests")) if out["state"] in FINISHED else []
    out["recheck_s"] = time.time() - t1
    out["bytes"] = sum(os.path.getsize(os.path.join(a, f)) for a, _d, fs in os.walk(final) for f in fs) \
        if os.path.isdir(final) else 0
    return out


def group_by(rows, key):
    out = {}
    for r in rows:
        out.setdefault(r[key], []).append(r)
    return out


