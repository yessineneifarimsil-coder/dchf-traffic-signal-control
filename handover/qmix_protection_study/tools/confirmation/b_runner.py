def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("action", choices=("plan", "measure", "freeze", "prepare", "preflight", "run", "progress", "analyse"))
    ap.add_argument("--root", required=True)
    ap.add_argument("--a-root", default=r"D:\QMIX_Results\comparators_robustness_profiles")
    ap.add_argument("--aext-root", default=r"D:\QMIX_Results\comparators_actuated_g5")
    ap.add_argument("--rob-root", default=r"D:\QMIX_Results\robustness_validation_2026-11-04")
    ap.add_argument("--a003-root", help="freeze: folder of amendment003 (A003), read only, to record statistics-1.2")
    ap.add_argument("--statistics", help="plan/freeze: statistics.py whose paired_crossed_bootstrap B uses "
                                         "(default: the frozen adaptive_qmix/protocol/statistics.py)")
    ap.add_argument("--approved-plan")
    ap.add_argument("--shard", default="0/1")
    ap.add_argument("--out", default=os.path.join("analysis", "confirmation"))
    ap.add_argument("--workers", type=int, default=WORKERS, help="measure: parallel processes (the planned 4)")
    ap.add_argument("--etapes-report", default=os.path.join("logs", "verify_etapes_B.txt"))
    ap.add_argument("--tests-report", default=os.path.join("logs", "tests_B.txt"))
    ap.add_argument("--no-recheck", action="store_true", help="analyse: do not re-read the cells from their gzip logs")
    a = ap.parse_args(argv)
    global STATISTICS_OVERRIDE
    STATISTICS_OVERRIDE = a.statistics
    try:
        if a.action == "plan":
            plan = build_plan(a.root, a.a_root, a.aext_root, a.rob_root)
            for p, learned, idqn, comp, labels in count_table(plan):
                print("{:32} QMIX/VDN {:4} | IDQN {:3} | comparator runs {:3} | comparators {}".format(p, learned, idqn, comp, labels))
            for p in PROFILES:
                m = plan["margins"][p]
                print("primary {:32} {:24} J_val {:.4f}  delta {:.4f} s".format(p, m["primary"], m["validation_J"], m["delta_s"]))
            print(json.dumps(plan["estimate"], indent=1))
            print("plan fingerprint:", plan["fingerprint"])
            return 0
        if a.action == "measure":
            mj = measure(a.root, a.a_root, a.aext_root, a.rob_root, workers=a.workers)
            print(json.dumps(dict((k, v) for k, v in mj.items() if k not in ("results", "code_sha256")), indent=1))
            print("RUN-IN OK: {} runs on design seeds, {} workers, {:.1f} runs/h".format(mj["runs"], mj["workers"],
                                                                                     mj["throughput_runs_per_h"]))
            return 0
        if a.action == "freeze":
            fr, plan = freeze(a.root, a.a_root, a.aext_root, a.rob_root, a.a003_root, a.etapes_report, a.tests_report)
            print(json.dumps(dict((k, fr[k]) for k in ("plan_fingerprint", "margins_sha256", "jobs", "statistics_1_2")), indent=1))
            print("FROZEN. Next: b-prepare", fr["plan_fingerprint"])
            return 0
        if a.action == "prepare":
            plan = prepare(a.root, a.approved_plan, a.a_root, a.aext_root, a.rob_root)
            print("prepared {} ({} runs)".format(a.root, len(plan["jobs"])))
            return 0
        if a.action == "preflight":
            return preflight(a.root)
        if a.action == "run":
            return run(a.root, a.shard)
        if a.action == "progress":
            return progress(a.root)
        result, missing = analyse(a.root, a.out, recheck=not a.no_recheck)
        for d in result["primary"]:
            print("F1 {:32} {:5} vs {:24} {}".format(d["profile"], d["method"], d["comparator"], d["category"]))
        for d in result["joint_learning"]:
            print("F2 {:32} {:5} vs {:24} {}".format(d["profile"], d["method"], d["reference"], d["category"]))
        print("missing cells:", len(missing), "| written:", a.out)
        return 0
    except (BError, SD.SeedError) as error:
        print("STOP:", error)
        return 1


