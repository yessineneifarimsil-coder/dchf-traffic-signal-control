def service_table(rows):
    """Every count, per (profile, method or comparator, arm), at the evaluation / model / traffic levels."""
    import confirmation_analysis as CA
    groups = {}
    for r in rows:
        groups.setdefault((r["scenario"], r["method"], r.get("arm", "")), []).append(r)
    out = []
    for (profile, method, arm), rs in sorted(groups.items()):
        learned = bool(arm)
        for event, _plain, test in EVENTS:
            u = CA.unit_counts(rs, test, learned=learned)
            row = {"profile": profile, "method": method, "arm": arm, "event": event,
                   "evaluations": u["evaluations"], "events": u["events"],
                   "traffics": u["traffics"]["units"], "traffics_with_event": u["traffics"]["units_with_event"],
                   "traffic_cp95_low": u["traffics"]["cp95"][0], "traffic_cp95_high": u["traffics"]["cp95"][1],
                   "traffic_upper95_if_zero": u["traffics"]["one_sided_upper95_if_zero"]}
            if learned:
                row.update({"models": u["models"]["units"], "models_with_event": u["models"]["units_with_event"],
                            "model_cp95_low": u["models"]["cp95"][0], "model_cp95_high": u["models"]["cp95"][1],
                            "model_upper95_if_zero": u["models"]["one_sided_upper95_if_zero"]})
            out.append(row)
    return out


