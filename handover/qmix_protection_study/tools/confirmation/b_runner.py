def load_selections(*roots):
    """Every sealed selection of the given campaign roots, checked against its own seal."""
    out = []
    for root in roots:
        folder = os.path.join(root, "selections") if root else ""
        if not root or not os.path.isdir(folder):
            continue
        for name in sorted(os.listdir(folder)):
            if not name.endswith(".json"):
                continue
            path = os.path.join(folder, name)
            payload = read_json(path)
            body = dict((k, v) for k, v in payload.items() if k != "sha256")
            if payload.get("sha256") != sha_obj(body):
                raise BError("selection {} does not match its seal".format(path))
            profile, suffix = name[:-5].split("__", 1)
            if suffix not in SELECTION_LABELS:
                raise BError("unknown selection kind {}".format(name))
            sel = payload["selected"]
            if not sel.get("valid") or sel.get("mean_J") is None:
                raise BError("selection {} is not valid".format(path))
            out.append({"profile": profile, "label": SELECTION_LABELS[suffix], "spec": sel["spec"],
                        "validation_J": float(sel["mean_J"]), "validation_seeds": sel["seeds"],
                        "file": path, "file_sha256": sha256_file(path)})
    return out


