def fixed_spec(key):
    import comparator_search as CS
    return CS.fixed_spec(key)


def comparators_by_profile(selections):
    out = {}
    for profile in PROFILES:
        labels = {}
        for label, key in FROZEN_COMPARATORS.items():
            labels[label] = {"kind": "canonical_mp"} if key is None else fixed_spec(key)
        for s in selections:
            if s["profile"] == profile:
                labels[s["label"]] = s["spec"]
        out[profile] = labels
    return out


def learned_models(rob_root, plan_conf):
    """The 20 frozen policies: QMIX and VDN entries of the robustness plan, equal to confirmation_plan.json."""
    path = os.path.join(rob_root, "plan.json")
    if not os.path.isfile(path):
        raise BError("robustness plan not found: {}".format(path))
    models = [m for m in read_json(path)["models"] if m["tag"].split("_", 1)[0] in METHODS]
    tags = sorted(m["tag"] for m in models)
    wanted = sorted(t for meth in METHODS for t in plan_conf["learned_policies"][meth])
    if tags != wanted:
        raise BError("robustness plan models {} differ from confirmation_plan.json {}".format(tags, wanted))
    return sorted(({"tag": m["tag"], "method": m["tag"].split("_", 1)[0], "sha256": m["sha256"]} for m in models),
                  key=lambda m: m["tag"])


def seed_of(tag):
    return int(tag.split("_seed")[1].split("_")[0])


def idqn_models(rob_root):
    """The 10 historical IDQN checkpoints of the robustness plan (training seeds 101-110, one each)."""
    models = [m for m in read_json(os.path.join(rob_root, "plan.json"))["models"] if m["tag"].split("_", 1)[0] == IDQN]
    seeds = sorted(seed_of(m["tag"]) for m in models)
    if seeds != list(TRAINING_SEEDS):
        raise BError("robustness plan IDQN checkpoints have training seeds {}; 101-110, one each, are required".format(seeds))
    return sorted(({"tag": m["tag"], "method": IDQN, "sha256": m["sha256"]} for m in models), key=lambda m: m["tag"])


def build_jobs(models, comparators, plan_conf):
    jobs = []
    for profile in PROFILES:
        for seed in plan_conf["traffic_seeds"][profile]:
            for m in models:
                if m["method"] == IDQN and profile not in IDQN_PROFILES:
                    continue
                for arm in (IDQN_ARMS if m["method"] == IDQN else ARMS):
                    jobs.append({"kind": "learned", "profile": profile, "seed": int(seed), "model": m["tag"],
                                 "method": m["method"], "arm": arm, "controller": "learned:" + arm,
                                 "checkpoint_sha256": m["sha256"],
                                 "directory": os.path.join("cells", profile, str(seed), m["tag"], arm)})
            by_spec = {}
            for label in sorted(comparators[profile]):
                spec = comparators[profile][label]
                by_spec.setdefault(sha_obj(spec), {"spec": spec, "labels": []})["labels"].append(label)
            for digest, entry in sorted(by_spec.items()):
                jobs.append({"kind": "comparator", "profile": profile, "seed": int(seed), "spec": entry["spec"],
                             "spec_sha256": digest, "labels": entry["labels"],
                             "directory": os.path.join("cells", profile, str(seed), "cmp_" + digest[:16])})
    return unique_jobs(jobs)


def unique_jobs(jobs):
    seen, out = set(), []
    for j in jobs:
        if j["directory"] not in seen:
            seen.add(j["directory"])
            out.append(j)
    return out


def estimate(jobs, measure):
    """Duration from the PARALLEL run-in (mean wall per kind / measured parallel efficiency); never a guarantee."""
    m = dict(DEFAULTS)
    m["seconds_learned_max"], m["seconds_comparator_max"] = m["seconds_learned"], m["seconds_comparator"]
    source = "defaults (B run-in not done yet): NOT measured with the planned parallelism"
    if measure:
        for k in ("seconds_learned", "seconds_comparator", "seconds_learned_max", "seconds_comparator_max",
                  "bytes_per_run", "parallel_efficiency"):
            m[k] = measure[k]
        source = "measure.json (parallel run-in, {} workers)".format(measure["workers"])
    learned = sum(1 for j in jobs if j["kind"] == "learned")
    comp = len(jobs) - learned
    eff = max(float(m["parallel_efficiency"]), 1e-6)
    expected = (learned * m["seconds_learned"] + comp * m["seconds_comparator"]) / WORKERS / eff
    pessimistic = (learned * m["seconds_learned_max"] + comp * m["seconds_comparator_max"]) / WORKERS / eff
    return {"runs": len(jobs), "learned": learned, "comparators": comp, "source": source,
            "wall_h_4_workers": round(expected / 3600.0, 2), "wall_h_4_workers_pessimistic": round(pessimistic / 3600.0, 2),
            "note": "estimate from the run-in, not a guarantee: runs that reach the 7,200 s cut-off, other loads on the "
                    "machine (IEV) or a sleep of Windows lengthen it",
            "disk_bytes": int(len(jobs) * m["bytes_per_run"]), "disk_gb": round(len(jobs) * m["bytes_per_run"] / 1e9, 2),
            "start_threshold_gb": round((len(jobs) * m["bytes_per_run"] + SAFETY_BYTES) / 1e9, 2),
            "bytes_per_run": m["bytes_per_run"]}


def check_confirmation_seeds(plan_conf):
    for profile in PROFILES:
        got = [int(s) for s in plan_conf["traffic_seeds"][profile]]
        if sorted(got) != list(SD.seeds(profile, "confirmation")):
            raise BError("{}: confirmation_plan.json seeds {} are not 8c51-8c60".format(profile, got))
        bad = set(got) & (set(range(3001, 3011)) | set(range(3101, 3121)) | set(range(2201, 2206)))
        if bad:
            raise BError("forbidden seeds {}".format(sorted(bad)))


def body_fingerprint(plan):
    return sha_obj(dict((k, v) for k, v in plan.items() if k not in ("fingerprint", "estimate")))


def build_plan(root, a_root, aext_root, rob_root):
    SD.check_disjoint()
    plan_conf = conf_plan()
    check_confirmation_seeds(plan_conf)
    selections = load_selections(a_root, aext_root)
    check_selections_complete(selections)
    models = learned_models(rob_root, plan_conf) + idqn_models(rob_root)
    comparators = comparators_by_profile(selections)
    primary = dict((p, choose_primary(selections, p)) for p in PROFILES)
    margins = dict((p, {"validation_J": primary[p]["validation_J"], "delta_s": margin(primary[p]["validation_J"], plan_conf),
                        "primary": primary[p]["label"]}) for p in PROFILES)
    jobs = build_jobs(models, comparators, plan_conf)
    for p in PROFILES:
        if primary[p]["label"] not in comparators[p]:
            raise BError("primary comparator {} of {} is not evaluated".format(primary[p]["label"], p))
    body = {"study": "confirmation_B", "profiles": list(PROFILES), "models": models,
            "confirmation_plan_fingerprint": plan_conf["fingerprint"],
            "selections": [dict((k, s[k]) for k in ("profile", "label", "validation_J", "file_sha256", "spec"))
                           for s in selections],
            "comparators": comparators, "primary": primary, "margins": margins, "jobs": jobs,
            "code_sha256": code_hashes(), "statistics_module_sha256": sha256_file(statistics_path(root))}
    body["fingerprint"] = body_fingerprint(body)
    measure_path = os.path.join(root, "measure.json")
    body["estimate"] = estimate(jobs, read_json(measure_path) if os.path.isfile(measure_path) else None)
    return body


def count_table(plan):
    rows = []
    for p in PROFILES:
        js = [j for j in plan["jobs"] if j["profile"] == p]
        rows.append((p, sum(1 for j in js if j["kind"] == "learned" and j["method"] != IDQN),
                     sum(1 for j in js if j["kind"] == "learned" and j["method"] == IDQN),
                     sum(1 for j in js if j["kind"] == "comparator"), sorted(plan["comparators"][p])))
    return rows


