def environment():
    """Python and SUMO versions of the machine running the run-in (recorded; the freeze requires 3.7 / 1.25)."""
    sumo, candidates = None, ["sumo"]
    if os.environ.get("SUMO_HOME"):
        candidates.append(os.path.join(os.environ["SUMO_HOME"], "bin", "sumo"))
    for exe in candidates:
        try:
            text = subprocess.run([exe, "--version"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                  timeout=60).stdout.decode("utf-8", "replace")
            sumo = next((line.strip() for line in text.splitlines() if line.strip()), "")[:120]
            break
        except (OSError, subprocess.SubprocessError) as error:
            sumo = "unknown ({!r})".format(error)
    return {"python": platform.python_version(), "sumo": sumo, "platform": platform.platform()}


def measure_jobs(models, comps):
    """12 runs on DESIGN seeds only, in the proportions of B as far as 12 runs allow (8 learned, 4 comparators)."""
    r0, r1, r3 = "R0_reference", "R1_sparse_secondary_heavy_main", "R3_time_varying"
    d0, d1, d3 = SD.seeds(r0, "comparator_design"), SD.seeds(r1, "comparator_design"), SD.seeds(r3, "comparator_design")
    pick = dict((meth, [m for m in models if m["method"] == meth][0]) for meth in (METHODS + (IDQN,)))

    def learned(profile, seed, meth, arm):
        m = pick[meth]
        return {"kind": "learned", "profile": profile, "seed": seed, "model": m["tag"], "method": meth, "arm": arm,
                "controller": "learned:" + arm, "checkpoint_sha256": m["sha256"]}

    def comparator(profile, seed, label):
        spec = comps[profile][label]
        return {"kind": "comparator", "profile": profile, "seed": seed, "spec": spec, "spec_sha256": sha_obj(spec),
                "labels": [label]}
    jobs = [learned(r1, d1[0], "qmix", "guarantee"), learned(r1, d1[0], "vdn", "none"),
            learned(r1, d1[1], "qmix", "none"), learned(r1, d1[1], "vdn", "guarantee"),
            learned(r3, d3[0], "qmix", "guarantee"), learned(r3, d3[0], "vdn", "guarantee"),
            learned(r0, d0[0], IDQN, "guarantee"), learned(r0, d0[1], IDQN, "guarantee"),
            comparator(r1, d1[0], "oft_g5"), comparator(r1, d1[0], "actuated_min7"),
            comparator(r0, d0[0], C19_LABEL), comparator(r3, d3[0], "tod_g5")]
    for k, j in enumerate(jobs):
        j["directory"] = os.path.join("runs", "{:02d}".format(k))
    return jobs


def _measure_one(task):
    """One run-in job, in a worker process: evaluate, finalise as in B, classify, re-read from gzip."""
    work_root, j, prefix, evaluator = task
    final = os.path.join(work_root, j["directory"])
    t0 = time.time()
    out = {"directory": j["directory"], "kind": j["kind"], "method": j.get("method", ""),
           "label": j.get("controller") or j["labels"][0],
           "profile": j["profile"], "seed": j["seed"]}
    try:
        (evaluator or default_evaluator)(work_root, j, prefix, final + ".tmp")
        finalize_cell(work_root, j, final + ".tmp", final, int(read_json(prefix + ".metadata.json")["scheduled_total"]))
    except Exception as error:  # noqa: BLE001 - reported to the parent, the run-in fails
        out.update({"wall_s": time.time() - t0, "state": "interrupted", "problems": [repr(error)]})
        return out
    out["wall_s"] = time.time() - t0
    out["state"], out["problems"] = classify(work_root, j)
    t1 = time.time()
    out["recheck"] = recheck_cell(work_root, j, os.path.join(work_root, "manifests")) if out["state"] in FINISHED else []
    out["recheck_s"] = time.time() - t1
    out["bytes"] = sum(os.path.getsize(os.path.join(a, f)) for a, _d, fs in os.walk(final) for f in fs) \
        if os.path.isdir(final) else 0
    return out


def measure(root, a_root, aext_root, rob_root, evaluator=None, workers=WORKERS):
    """Parallel run-in on design seeds: the throughput of B is measured with the planned parallelism."""
    if os.path.exists(os.path.join(root, "measure.json")):
        raise BError("measure.json exists (the run-in is done once per B root)")
    plan_conf = conf_plan()
    selections = load_selections(a_root, aext_root)
    models = learned_models(rob_root, plan_conf) + idqn_models(rob_root)
    jobs = measure_jobs(models, comparators_by_profile(selections))
    work_root = os.path.join(root, "measure_runs")
    if os.path.isdir(os.path.join(work_root, "runs")):
        os.rename(os.path.join(work_root, "runs"), os.path.join(work_root, "runs_failed_" + time.strftime("%Y%m%d_%H%M%S")))
    os.makedirs(os.path.join(work_root, "manifests"), exist_ok=True)
    os.makedirs(os.path.join(work_root, "checkpoints"), exist_ok=True)
    os.makedirs(os.path.join(work_root, "runs"), exist_ok=True)
    for m in dict((j["model"], j) for j in jobs if j["kind"] == "learned"):
        sha = [x for x in models if x["tag"] == m][0]["sha256"]
        src = os.path.join(rob_root, "checkpoints", m + ".pth")
        if sha256_file(src) != sha:
            raise BError("robustness copy of {} has another SHA-256".format(m))
        shutil.copyfile(src, os.path.join(work_root, "checkpoints", m + ".pth"))
    tasks = []
    for j in jobs:
        if SD.role_of(j["profile"], j["seed"]) != "comparator_design":
            raise BError("the run-in uses design seeds only")
        prefix = os.path.join(work_root, "manifests", "{}_{}".format(j["profile"], j["seed"]))
        if not os.path.exists(prefix + ".metadata.json"):
            manifest_writer(j["profile"], j["seed"], prefix)
        tasks.append((work_root, j, prefix, evaluator))
    t0 = time.time()
    if workers <= 1:
        results = [_measure_one(t) for t in tasks]
    else:
        from concurrent.futures import ProcessPoolExecutor
        with ProcessPoolExecutor(max_workers=workers) as pool:
            results = list(pool.map(_measure_one, tasks))
    elapsed = time.time() - t0
    bad = [r for r in results if r["state"] not in FINISHED or r["recheck"]]
    walls = dict((k, [r["wall_s"] for r in results if r["kind"] == k]) for k in ("learned", "comparator"))
    payload = {"ok": not bad, "workers": workers, "runs": len(results), "elapsed_s": elapsed,
               "throughput_runs_per_h": len(results) / elapsed * 3600.0 if elapsed > 0 else None,
               "parallel_efficiency": min(1.0, sum(r["wall_s"] for r in results) / (max(workers, 1) * elapsed))
               if elapsed > 0 else 1.0,
               "seconds_learned": sum(walls["learned"]) / len(walls["learned"]),
               "seconds_learned_max": max(walls["learned"]),
               "seconds_comparator": sum(walls["comparator"]) / len(walls["comparator"]),
               "seconds_comparator_max": max(walls["comparator"]),
               "bytes_per_run": max(r.get("bytes", 0) for r in results),
               "recheck_s_per_run": sum(r.get("recheck_s", 0) for r in results) / len(results),
               "results": results, "environment": environment(), "code_sha256": code_hashes(),
               "seeds": "design seeds only (never confirmation): {}".format(sorted(set((j["profile"], j["seed"]) for j in jobs)))}
    if bad:
        write_json(os.path.join(root, "measure_failed_{}.json".format(time.strftime("%Y%m%d_%H%M%S"))), payload)
        raise BError("run-in failed for {} run(s): {}. Do not freeze; report this.".format(
            len(bad), "; ".join("{} {} {} {}: {} {}".format(r["directory"], r["profile"], r["seed"], r["label"], r["state"],
                                                          (r["problems"] + r.get("recheck", []))[:3]) for r in bad)))
    write_json(os.path.join(root, "measure.json"), payload)
    return payload


