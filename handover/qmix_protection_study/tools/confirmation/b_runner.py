def expected_counts(plan):
    """Expected evaluations per (profile, method or comparator label, arm), from the plan's jobs (IDQN: R0 only)."""
    out = {}
    for j in plan["jobs"]:
        keys = [(j["profile"], j["method"], j["arm"])] if j["kind"] == "learned" else \
            [(j["profile"], label, "") for label in j["labels"]]
        for k in keys:
            out[k] = out.get(k, 0) + 1
    return out


def service_table(rows, plan):
    """Every count, per (profile, method or comparator, arm), with the plan's expected count; unit-level intervals
    within the profile only (models / traffics), never on pooled evaluations."""
    import confirmation_analysis as CA
    groups = {}
    for r in rows:
        groups.setdefault((r["scenario"], r["method"], r.get("arm", "")), []).append(r)
    out = []
    for key, expected in sorted(expected_counts(plan).items()):
        profile, method, arm = key
        rs = groups.get(key, [])
        learned = bool(arm)
        for event, _plain, test in EVENTS:
            row = {"profile": profile, "method": method, "arm": arm, "event": event, "expected": expected,
                   "evaluations": len(rs), "events": sum(1 for r in rs if test(r))}
            if rs:
                u = CA.unit_counts(rs, test, learned=learned)
                for unit in (("models", "traffics") if learned else ("traffics",)):
                    v = u[unit]
                    row.update({unit: v["units"], unit + "_with_event": v["units_with_event"],
                                unit + "_cp95_two_sided_low": v["cp95_two_sided"][0],
                                unit + "_cp95_two_sided_high": v["cp95_two_sided"][1],
                                unit + "_upper95_one_sided": v["upper95_one_sided"]})
            out.append(row)
    return out


def panel_of(rows, profile, method, arm, field, cleared_only):
    out = {}
    for r in rows:
        if r["scenario"] == profile and r.get("method") == method and r.get("arm", "") == arm:
            v = r[field]
            if v in (None, "") or (cleared_only and r["status"] != "CLEARED"):
                continue
            key = (int(r["model"].split("_seed")[1][:3]) if r.get("model") else None, int(r["seed"]))
            out[key] = float(v)
    return out


def paired(a, b):
    keys = sorted(set(a) & set(b))
    d = [a[k] - b[k] for k in keys]
    return {"pairs": len(keys), "mean_difference": (sum(d) / len(d)) if d else None}


def guarantee_effects(rows, plan):
    """guarantee - none on the same model and traffic, per profile and method (IDQN: R0), with interventions."""
    exp = expected_counts(plan)
    out = []
    for (profile, method, arm), n_exp in sorted(exp.items()):
        if arm != "guarantee" or (profile, method, "none") not in exp:
            continue
        g = [r for r in rows if r["scenario"] == profile and r.get("method") == method and r.get("arm") == "guarantee"]
        n = [r for r in rows if r["scenario"] == profile and r.get("method") == method and r.get("arm") == "none"]
        entry = {"profile": profile, "method": method}
        for name, rs, e in (("guarantee", g, n_exp), ("none", n, exp[(profile, method, "none")])):
            entry[name] = {"present": len(rs), "expected": e, "failures": sum(1 for r in rs if r["status"] != "CLEARED"),
                           "interventions_during_demand": sum(int(r.get("interventions_guarantee_demand") or 0) for r in rs),
                           "interventions_after_demand": sum(int(r.get("interventions_guarantee_after") or 0) for r in rs),
                           "runs_with_intervention_during_demand": sum(1 for r in rs if int(r.get("interventions_guarantee_demand") or 0) > 0)}
        entry["J_guarantee_minus_none_pairs_both_cleared"] = paired(
            panel_of(rows, profile, method, "guarantee", "J_primary_s", True), panel_of(rows, profile, method, "none", "J_primary_s", True))
        entry["D_bar_guarantee_minus_none_all_valid_pairs"] = paired(
            panel_of(rows, profile, method, "guarantee", "D_bar_s", False), panel_of(rows, profile, method, "none", "D_bar_s", False))
        entry["pairs_expected"] = n_exp
        out.append(entry)
    return out


def dbar_contrasts(rows, result, ST, reps):
    """D_bar differences of the 12 confirmatory contrasts over ALL technically valid pairs, failures included
    (descriptive, 95 % crossed bootstrap when the panel is complete)."""
    out = []
    for d in result["primary"] + result["joint_learning"]:
        prof, m = d["profile"], d["method"]
        a = panel_of(rows, prof, m, "guarantee", "D_bar_s", False)
        if "comparator" in d:
            c = dict((k[1], v) for k, v in panel_of(rows, prof, d["comparator"], "", "D_bar_s", False).items())
            diffs = [v - c[k[1]] for k, v in a.items() if k[1] in c]
            entry = {"profile": prof, "method": m, "against": d["comparator"], "pairs": len(diffs),
                     "mean_difference": (sum(diffs) / len(diffs)) if diffs else None}
            panel = {}
            for (seed, traffic), v in a.items():
                panel.setdefault(seed, {})[traffic] = v
            complete = len(a) == 100 and len(c) == 10 and all(len(v) == 10 for v in panel.values())
            if complete:
                b = ST.paired_crossed_bootstrap(panel, c, replicates=reps, confidence=0.95, comparator_kind=ST.COMPARATOR_DETERMINISTIC)
                entry["ci_95"] = [b["ci_low"], b["ci_high"]]
        else:
            r = panel_of(rows, prof, d["reference"], "guarantee", "D_bar_s", False)
            entry = dict({"profile": prof, "method": m, "against": d["reference"]}, **paired(a, r))
            pa, pr = {}, {}
            for (seed, traffic), v in a.items():
                pa.setdefault(seed, {})[traffic] = v
            for (seed, traffic), v in r.items():
                pr.setdefault(seed, {})[traffic] = v
            if entry["pairs"] == 100 and sorted(pa) == sorted(pr) and all(len(v) == 10 for v in list(pa.values()) + list(pr.values())):
                b = ST.paired_crossed_bootstrap(pa, pr, replicates=reps, confidence=0.95, comparator_kind=ST.COMPARATOR_LEARNED)
                entry["ci_95"] = [b["ci_low"], b["ci_high"]]
        entry["status"] = "descriptive; D_bar over the demand window, failures included; not a decision"
        out.append(entry)
    return out


