def prepare(root, approved, a_root, aext_root, rob_root):
    plan = build_plan(root, a_root, aext_root, rob_root)
    check_frozen(root, plan)
    if approved != plan["fingerprint"]:
        raise BError("--approved-plan must be the frozen fingerprint {}".format(plan["fingerprint"]))
    if os.path.exists(os.path.join(root, "plan.json")):
        raise BError("already prepared")
    os.makedirs(os.path.join(root, "checkpoints"), exist_ok=True)
    for m in plan["models"]:
        src = os.path.join(rob_root, "checkpoints", m["tag"] + ".pth")
        dst = os.path.join(root, "checkpoints", m["tag"] + ".pth")
        if sha256_file(src) != m["sha256"]:
            raise BError("robustness copy of {} has another SHA-256".format(m["tag"]))
        shutil.copyfile(src, dst)
        if sha256_file(dst) != m["sha256"]:
            raise BError("copy of {} differs".format(m["tag"]))
    write_confirmation_manifests(root, plan)
    write_json(os.path.join(root, "manifests_sha256.json"),
               dict((n, sha256_file(os.path.join(root, "manifests", n))) for n in sorted(os.listdir(os.path.join(root, "manifests")))))
    write_json(os.path.join(root, "plan.json"), plan)
    return plan


