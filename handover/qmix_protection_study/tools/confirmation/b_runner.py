def cell_rows(root, plan, recheck=True):
    rows, missing = [], []
    manifests = os.path.join(root, "manifests")
    for j in plan["jobs"]:
        state, _why = classify(root, j)
        if state not in FINISHED:
            missing.append({"directory": j["directory"], "state": state})
            continue
        if recheck:
            diff = recheck_cell(root, j, manifests)
            if diff:
                missing.append({"directory": j["directory"], "state": "recheck_mismatch", "problems": diff})
                continue
        s = read_json(os.path.join(root, j["directory"], "cell_summary.json"))
        base = {"scenario": j["profile"], "seed": str(j["seed"]), "status": s["status"],
                "J_primary_s": "" if s.get("J_primary_s") is None else repr(float(s["J_primary_s"])),
                "open_wait_at_end_s": "" if s.get("open_wait_at_end_s") is None else str(s["open_wait_at_end_s"]),
                "vehicles_waiting_ge_300s": str(s.get("vehicles_waiting_ge_300s") or 0),
                "D_bar_s": s.get("D_bar_s"), "mean_completed_time_loss_s": s.get("mean_completed_time_loss_s"),
                "max_vehicle_waiting_s": s.get("max_vehicle_waiting_s")}
        if j["kind"] == "learned":
            rows.append(dict(base, controller=j["controller"], model=j["model"], method=j["method"], arm=j["arm"]))
        else:
            for label in j["labels"]:
                rows.append(dict(base, controller=label, model="", method=label, arm=""))
    return rows, missing


