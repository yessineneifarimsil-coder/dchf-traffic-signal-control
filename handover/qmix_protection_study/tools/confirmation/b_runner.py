    os.makedirs(os.path.join(work_root, "manifests"), exist_ok=True)
    os.makedirs(os.path.join(work_root, "checkpoints"), exist_ok=True)
    os.makedirs(os.path.join(work_root, "runs"), exist_ok=True)
    for m in dict((j["model"], j) for j in jobs if j["kind"] == "learned"):
        sha = [x for x in models if x["tag"] == m][0]["sha256"]
        src = os.path.join(rob_root, "checkpoints", m + ".pth")
        if sha256_file(src) != sha:
            raise BError("robustness copy of {} has another SHA-256".format(m))
        shutil.copyfile(src, os.path.join(work_root, "checkpoints", m + ".pth"))
    tasks = []
    for j in jobs:
        if SD.role_of(j["profile"], j["seed"]) != "comparator_design":
            raise BError("the run-in uses design seeds only")
        prefix = os.path.join(work_root, "manifests", "{}_{}".format(j["profile"], j["seed"]))
        if not os.path.exists(prefix + ".metadata.json"):
            manifest_writer(j["profile"], j["seed"], prefix)
        tasks.append((work_root, j, prefix, evaluator))
    t0 = time.time()
    if workers <= 1:
        results = [_measure_one(t) for t in tasks]
    else:
        from concurrent.futures import ProcessPoolExecutor
        with ProcessPoolExecutor(max_workers=workers) as pool:
            results = list(pool.map(_measure_one, tasks))
    elapsed = time.time() - t0
    bad = [r for r in results if r["state"] not in FINISHED or r["recheck"]]
    walls = dict((k, [r["wall_s"] for r in results if r["kind"] == k]) for k in ("learned", "comparator"))
    payload = {"ok": not bad, "workers": workers, "runs": len(results), "elapsed_s": elapsed,
               "throughput_runs_per_h": len(results) / elapsed * 3600.0 if elapsed > 0 else None,
               "parallel_efficiency": min(1.0, sum(r["wall_s"] for r in results) / (max(workers, 1) * elapsed))
               if elapsed > 0 else 1.0,
               "seconds_learned": sum(walls["learned"]) / len(walls["learned"]),
               "seconds_learned_max": max(walls["learned"]),
               "seconds_comparator": sum(walls["comparator"]) / len(walls["comparator"]),
               "seconds_comparator_max": max(walls["comparator"]),
               "bytes_per_run": max(r.get("bytes", 0) for r in results),
               "recheck_s_per_run": sum(r.get("recheck_s", 0) for r in results) / len(results),
               "finalize_gzip_s_per_run": sum(r.get("finalize_gzip_s", 0) for r in results) / len(results),
               "by_type": dict((t, {"runs": len(v), "mean_wall_s": sum(x["wall_s"] for x in v) / len(v),
                                    "max_wall_s": max(x["wall_s"] for x in v),
                                    "mean_bytes": sum(x.get("bytes", 0) for x in v) / len(v)})
                               for t, v in sorted(group_by(results, "type").items())),
               "results": results, "environment": environment(), "code_sha256": code_hashes(),
               "seeds": "design seeds only (never confirmation): {}".format(sorted(set((j["profile"], j["seed"]) for j in jobs)))}
    if bad:
        write_json(os.path.join(root, "measure_failed_{}.json".format(time.strftime("%Y%m%d_%H%M%S"))), payload)
        raise BError("run-in failed for {} run(s): {}. Do not freeze; report this.".format(
            len(bad), "; ".join("{} {} {} {}: {} {}".format(r["directory"], r["profile"], r["seed"], r["label"], r["state"],
                                                          (r["problems"] + r.get("recheck", []))[:3]) for r in bad)))
    write_json(os.path.join(root, "measure.json"), payload)
    return payload


