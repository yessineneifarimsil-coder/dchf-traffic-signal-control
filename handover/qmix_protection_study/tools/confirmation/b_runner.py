def classify(root, j):
    d = os.path.join(root, j["directory"])
    if not os.path.isdir(d):
        return ("interrupted", ["work folder left by an interrupted run"]) if os.path.isdir(d + ".tmp") else ("not_started", [])
    path = os.path.join(d, "evaluation_metrics.json")
    if not os.path.isfile(path):
        return "interrupted", ["no evaluation_metrics.json"]
    try:
        m = read_json(path)
        summary = read_json(os.path.join(d, "cell_summary.json"))
    except (ValueError, OSError, UnicodeDecodeError) as error:
        return "corrupted", ["unreadable: {}".format(error)]
    problems = ["missing " + n for n in REQUIRED + (REQUIRED_LEARNED if j["kind"] == "learned" else ())
                if not os.path.isfile(os.path.join(d, n))]
    if m.get("scenario") != j["profile"] or str(m.get("traffic_seed")) != str(j["seed"]):
        problems.append("identity (scenario/seed) differs")
    if j["kind"] == "learned":
        if m.get("controller") != j["controller"] or m.get("checkpoint_sha256") != j["checkpoint_sha256"]:
            problems.append("identity (controller/checkpoint) differs")
    elif m.get("comparator_spec_sha256") != j["spec_sha256"]:
        problems.append("comparator spec differs")
    status = m.get("clearance_status")
    if status not in ("CLEARED", "CLEARANCE_FAILURE") or summary.get("status") != status:
        problems.append("status {!r}".format(status))
    problems.extend("cell_metrics: " + p for p in summary.get("problems") or [])   # e.g. J differs from tripinfo
    if problems:
        return "corrupted", problems
    return ("complete" if status == "CLEARED" else "scientific_failure"), []


def summarise_cell(j, work, n_scheduled):
    """robustness_analysis.cell_metrics on the plain logs (before gzip); returns (summary, problems)."""
    import robustness_analysis as RA
    cell = {"scenario": j["profile"], "seed": j["seed"], "model": j.get("model", ""),
            "controller": j.get("controller") or "comparator:" + j["spec"]["kind"]}
    return RA.cell_metrics(cell, work, n_scheduled)


def finalize_cell(root, j, work, final, n_scheduled):
    """Set metrics aside, summarise, gzip, rename, restore metrics LAST."""
    metrics = os.path.join(work, "evaluation_metrics.json")
    pending = metrics + ".pending"
    os.rename(metrics, pending)
    shutil.copyfile(pending, metrics)                    # cell_metrics reads it; removed again below
    try:
        summary, problems = summarise_cell(j, work, n_scheduled)
    finally:
        os.remove(metrics)
    summary["problems"] = problems
    write_json(os.path.join(work, "cell_summary.json"), summary)
    for name in GZIPPED:
        src = os.path.join(work, name)
        if os.path.isfile(src):
            with open(src, "rb") as a, gzip.open(src + ".gz", "wb") as b:
                shutil.copyfileobj(a, b)
            os.remove(src)
    os.rename(work, final)
    os.rename(os.path.join(final, "evaluation_metrics.json.pending"), os.path.join(final, "evaluation_metrics.json"))


RECHECKED = ("status", "J_primary_s", "D_bar_s", "mean_completed_time_loss_s", "max_vehicle_waiting_s",
             "vehicles_waiting_ge_300s", "open_wait_at_end_s", "N")


def same(a, b):
    if isinstance(a, float) or isinstance(b, float):
        try:
            return abs(float(a) - float(b)) <= 1e-9 * max(1.0, abs(float(a)))
        except (TypeError, ValueError):
            return a == b
    return a == b


def recheck_cell(root, j, manifests):
    """Re-read a FINISHED cell from its gzip logs: decompress into a scratch folder under root, recompute the summary
    with the same reader (robustness_analysis.cell_metrics) and compare it with cell_summary.json."""
    d = os.path.join(root, j["directory"])
    n = int(read_json(os.path.join(manifests, "{}_{}.metadata.json".format(j["profile"], j["seed"])))["scheduled_total"])
    scratch = tempfile.mkdtemp(prefix="recheck_", dir=root)
    try:
        for name in os.listdir(d):
            src = os.path.join(d, name)
            if name.endswith(".gz"):
                with gzip.open(src, "rb") as a, open(os.path.join(scratch, name[:-3]), "wb") as b:
                    shutil.copyfileobj(a, b)
            elif os.path.isfile(src):
                shutil.copyfile(src, os.path.join(scratch, name))
        again, problems = summarise_cell(j, scratch, n)
    except Exception as error:  # noqa: BLE001 - an unreadable gzip log is a finding, not a crash
        return ["re-read from gzip failed: {!r}".format(error)]
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    stored = read_json(os.path.join(d, "cell_summary.json"))
    out = ["{}: stored {!r}, re-read {!r}".format(k, stored.get(k), again.get(k)) for k in RECHECKED
           if k in stored and not same(stored.get(k), again.get(k))]
    if sorted(problems) != sorted(stored.get("problems") or []):
        out.append("problems differ after re-read: {}".format(problems))
    return out


def default_evaluator(root, j, prefix, work):
    if j["kind"] == "learned":
        import evaluate_any as ea
        ea.evaluate(j["controller"], prefix, work, checkpoint=os.path.join(root, "checkpoints", j["model"] + ".pth"))
    else:
        import evaluate_ext as ex
        ex.evaluate(j["spec"], prefix, work, counters=True, compact=False)


def free_bytes(path):
    path = os.path.abspath(path)
    while not os.path.exists(path):
        path = os.path.dirname(path)
    return shutil.disk_usage(path).free


def check_disk(root, remaining, bytes_per_run, free=None):
    need = remaining * bytes_per_run + SAFETY_BYTES
    have = free_bytes(root) if free is None else free
    if have < need:
        raise BError("not enough disk space: {:.2f} GB free, {} runs x {:.1f} MB + 4 GB = {:.2f} GB needed. "
                     "Free space first (ETAPES.cmd disk-audit; archive to another drive; deleting campaign A data is "
                     "disabled in this delivery).".format(
                         have / 1e9, remaining, bytes_per_run / 1e6, need / 1e9))
    return need


def shard(jobs, spec):
    i, n = (int(x) for x in spec.split("/"))
    if not 0 <= i < n:
        raise BError("bad shard {}".format(spec))
    return [j for pos, j in enumerate(unique_jobs(jobs)) if pos % n == i]


def run(root, shard_spec, evaluator=None, free=None):
    plan = load_plan(root)
    mine = shard(plan["jobs"], shard_spec)
    remaining = [j for j in mine if classify(root, j)[0] not in FINISHED]
    check_disk(root, len(remaining), plan["estimate"]["bytes_per_run"], free)
    evaluator = evaluator or default_evaluator
    corrupted, unfinished = [], []
    i, n = shard_spec.split("/")
    log = open(os.path.join(root, "run_log_shard{}of{}.jsonl".format(i, n)), "a")
    for j in mine:
        if SD.role_of(j["profile"], j["seed"]) != "confirmation":
            raise BError("not a confirmation seed: {}".format(j["directory"]))
        state, why = classify(root, j)
        if state in FINISHED:
            continue
        if state == "corrupted":
            print("CORRUPTED, preserved, NOT rerun: {} ({})".format(j["directory"], "; ".join(why)))
            corrupted.append(j["directory"])
            continue
        final = os.path.join(root, j["directory"])
        work = final + ".tmp"
        if state == "interrupted":
            if os.path.exists(final + ".incomplete1"):
                print("INTERRUPTED TWICE, preserved, NOT rerun: {}".format(j["directory"]))
                unfinished.append(j["directory"])
                continue
            os.rename(final if os.path.isdir(final) else work, final + ".incomplete1")
        os.makedirs(os.path.dirname(final), exist_ok=True)
        prefix = os.path.join(root, "manifests", "{}_{}".format(j["profile"], j["seed"]))
        t0 = time.time()
        try:
            evaluator(root, j, prefix, work)
            n_sched = int(read_json(prefix + ".metadata.json")["scheduled_total"])
            finalize_cell(root, j, work, final, n_sched)
        except Exception as error:  # noqa: BLE001 - technical interruption; the resume rule applies
            print("INTERRUPTED: {} ({!r})".format(j["directory"], error))
        state, why = classify(root, j)
        log.write(json.dumps({"dir": j["directory"], "state": state, "problems": why, "wall_s": time.time() - t0}) + "\n")
        log.flush()
        if state == "corrupted":
            corrupted.append(j["directory"])
        elif state not in FINISHED:
            unfinished.append(j["directory"])
    log.close()
    print("shard {}: {} corrupted, {} not finished".format(shard_spec, len(corrupted), len(unfinished)))
    return 5 if corrupted else (3 if unfinished else 0)


def preflight(root, free=None):
    """Before launching workers: frozen plan and code, prepared, enough disk for ALL remaining runs."""
    plan = load_plan(root)
    remaining = [j for j in plan["jobs"] if classify(root, j)[0] not in FINISHED]
    need = check_disk(root, len(remaining), plan["estimate"]["bytes_per_run"], free)
    print("preflight OK: {} runs to do, {:.2f} GB required with the 4 GB margin, plan {}".format(
        len(remaining), need / 1e9, plan["fingerprint"]))
    return 0


def progress(root):
    plan = load_plan(root)
    states = {}
    for j in plan["jobs"]:
        states.setdefault(classify(root, j)[0], []).append(j["directory"])
    total = len(plan["jobs"])
    done = sum(len(states.get(s, [])) for s in FINISHED)
    print("finished {}/{} (scientific failures {}) | corrupted {} | interrupted {} | not started {}".format(
        done, total, len(states.get("scientific_failure", [])), len(states.get("corrupted", [])),
        len(states.get("interrupted", [])), len(states.get("not_started", []))))
    for d in states.get("corrupted", [])[:20]:
        print("  CORRUPTED (preserved, not rerun):", d)
    if states.get("corrupted"):
        return 5
    return 0 if done == total else 3


