def min_green_contract(j):
    """The realised minimum green the evaluated controller itself guarantees (None: no realised-minimum contract)."""
    if j["kind"] == "learned":
        return LEARNED_MIN_GREEN_S
    kind = j["spec"]["kind"]
    if kind == "actuated":
        return 7                                         # tools/comparators/controllers.py MIN_GREEN_S
    if kind == "actuated_g5":
        return 5                                         # tools/comparators_ext/controllers_g5.py MIN_GREEN_G5_S
    if kind == "canonical_mp":
        return MP_MIN_GREEN_S
    return None                                          # fixed / tod: offset or period change can cut a first spell


def contract_problems(j, s):
    """Technical contracts of one cell, from its summary (recomputed from the traces by cell_metrics)."""
    out = []
    for k in CRITICAL + (CRITICAL_LEARNED if j["kind"] == "learned" else ()):
        if k not in s:
            out.append("critical field {} missing".format(k))
    if out:
        return out
    if j["kind"] == "learned":
        if s["sumo_mismatch_s"] != 0:
            out.append("SUMO signal mismatch {} s (must be 0 in every learned arm)".format(s["sumo_mismatch_s"]))
        if j["arm"] == "guarantee":
            for k in ("max_counter_s", "max_counter_recomputed_s"):
                if s[k] is None or s[k] > COUNTER_BOUND_S:
                    out.append("{} = {} above the guarantee bound {} s".format(k, s[k], COUNTER_BOUND_S))
    if s["counter_rows_differing"]:
        out.append("{} logged counter rows differ from their recomputation".format(s["counter_rows_differing"]))
    if s["max_counter_s"] != s["max_counter_recomputed_s"]:
        out.append("max counter logged {} differs from recomputed {}".format(s["max_counter_s"], s["max_counter_recomputed_s"]))
    floor = min_green_contract(j)
    if floor is not None and s["shortest_green_s"] is not None and s["shortest_green_s"] < floor:
        out.append("shortest green {} s below the controller's own minimum {} s".format(s["shortest_green_s"], floor))
    if s["N"] != s["tripinfo_rows"]:
        out.append("tripinfo rows {} for N = {}".format(s["tripinfo_rows"], s["N"]))
    return out


def classify(root, j):
    d = os.path.join(root, j["directory"])
    if not os.path.isdir(d):
        return ("interrupted", ["work folder left by an interrupted run"]) if os.path.isdir(d + ".tmp") else ("not_started", [])
    path = os.path.join(d, "evaluation_metrics.json")
    if not os.path.isfile(path):
        return "interrupted", ["no evaluation_metrics.json"]
    try:
        m = read_json(path)
        summary = read_json(os.path.join(d, "cell_summary.json"))
    except (ValueError, OSError, UnicodeDecodeError) as error:
        return "corrupted", ["unreadable: {}".format(error)]
    problems = ["missing " + n for n in REQUIRED + (REQUIRED_LEARNED if j["kind"] == "learned" else ())
                if not os.path.isfile(os.path.join(d, n))]
    if m.get("scenario") != j["profile"] or str(m.get("traffic_seed")) != str(j["seed"]):
        problems.append("identity (scenario/seed) differs")
    if j["kind"] == "learned":
        if m.get("controller") != j["controller"] or m.get("checkpoint_sha256") != j["checkpoint_sha256"]:
            problems.append("identity (controller/checkpoint) differs")
    elif m.get("comparator_spec_sha256") != j["spec_sha256"]:
        problems.append("comparator spec differs")
    status = m.get("clearance_status")
    if status not in ("CLEARED", "CLEARANCE_FAILURE") or summary.get("status") != status:
        problems.append("status {!r}".format(status))
    problems.extend("cell_metrics: " + p for p in summary.get("problems") or [])   # e.g. J differs from tripinfo
    problems.extend("TECHNICAL CONTRACT: " + p for p in contract_problems(j, summary))
    if problems:
        return "corrupted", problems
    return ("complete" if status == "CLEARED" else "scientific_failure"), []


def summarise_cell(j, work, n_scheduled):
    """robustness_analysis.cell_metrics on the plain logs (before gzip); returns (summary, problems)."""
    import robustness_analysis as RA
    cell = {"scenario": j["profile"], "seed": j["seed"], "model": j.get("model", ""),
            "controller": j.get("controller") or "comparator:" + j["spec"]["kind"]}
    return RA.cell_metrics(cell, work, n_scheduled)


def finalize_cell(root, j, work, final, n_scheduled):
    """Set metrics aside, summarise, gzip, rename, restore metrics LAST."""
    metrics = os.path.join(work, "evaluation_metrics.json")
    pending = metrics + ".pending"
    os.rename(metrics, pending)
    shutil.copyfile(pending, metrics)                    # cell_metrics reads it; removed again below
    try:
        summary, problems = summarise_cell(j, work, n_scheduled)
    finally:
        os.remove(metrics)
    summary["problems"] = problems
    write_json(os.path.join(work, "cell_summary.json"), summary)
    for name in GZIPPED:
        src = os.path.join(work, name)
        if os.path.isfile(src):
            with open(src, "rb") as a, gzip.open(src + ".gz", "wb") as b:
                shutil.copyfileobj(a, b)
            os.remove(src)
    os.rename(work, final)
    os.rename(os.path.join(final, "evaluation_metrics.json.pending"), os.path.join(final, "evaluation_metrics.json"))


def same(a, b):
    """Equality of two JSON values, floats within 1e-9 relative (the same reader on the same traces)."""
    if isinstance(a, bool) or isinstance(b, bool):
        return a is b
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return abs(float(a) - float(b)) <= 1e-9 * max(1.0, abs(float(a)))
    if isinstance(a, list) and isinstance(b, list):
        return len(a) == len(b) and all(same(x, y) for x, y in zip(a, b))
    if isinstance(a, dict) and isinstance(b, dict):
        return set(a) == set(b) and all(same(a[k], b[k]) for k in a)
    return a == b


def recheck_cell(root, j, manifests):
    """Re-read a FINISHED cell from its gzip logs: decompress into a scratch folder under root, recompute the summary
    with the same reader (robustness_analysis.cell_metrics) and compare it with cell_summary.json."""
    d = os.path.join(root, j["directory"])
    n = int(read_json(os.path.join(manifests, "{}_{}.metadata.json".format(j["profile"], j["seed"])))["scheduled_total"])
    scratch = tempfile.mkdtemp(prefix="recheck_", dir=root)
    try:
        for name in os.listdir(d):
            src = os.path.join(d, name)
            if name.endswith(".gz"):
                with gzip.open(src, "rb") as a, open(os.path.join(scratch, name[:-3]), "wb") as b:
                    shutil.copyfileobj(a, b)
            elif os.path.isfile(src):
                shutil.copyfile(src, os.path.join(scratch, name))
        again, problems = summarise_cell(j, scratch, n)
    except Exception as error:  # noqa: BLE001 - an unreadable gzip log is a finding, not a crash
        return ["re-read from gzip failed: {!r}".format(error)]
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    stored = read_json(os.path.join(d, "cell_summary.json"))
    again = json.loads(json.dumps(again))                 # same JSON types as the stored summary
    keys = sorted((set(stored) | set(again)) - {"problems"})
    out = ["{}: stored {!r}, re-read {!r}".format(k, stored.get(k, "<absent>"), again.get(k, "<absent>"))
           for k in keys if k not in stored or k not in again or not same(stored[k], again[k])]
    if sorted(problems) != sorted(stored.get("problems") or []):
        out.append("problems differ after re-read: {}".format(problems))
    out.extend("TECHNICAL CONTRACT (re-read): " + p for p in contract_problems(j, again))
    out.extend("cell_metrics (re-read): " + p for p in problems)
    return out


