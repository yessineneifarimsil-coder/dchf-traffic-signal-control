def check_freeze_prerequisites(root, etapes_report, tests_report):
    """The definitive freeze needs the finished, TESTED code: the parallel run-in passed under Python 3.7 / SUMO 1.25
    with exactly this code, the Windows check of ETAPES.cmd reports 0 failures and the unit tests report OK."""
    path = os.path.join(root, "measure.json")
    if not os.path.isfile(path):
        raise BError("no run-in: run `measure` (ETAPES.cmd b-measure) before the freeze")
    mj = read_json(path)
    if not mj.get("ok"):
        raise BError("the run-in did not pass: do not freeze")
    env = mj.get("environment", {})
    if not str(env.get("python", "")).startswith(REQUIRED_ENV["python"]) or REQUIRED_ENV["sumo"] not in str(env.get("sumo", "")):
        raise BError("run-in environment {} is not Python {}x / SUMO {}".format(env, REQUIRED_ENV["python"], REQUIRED_ENV["sumo"]))
    if mj.get("code_sha256") != code_hashes():
        changed = sorted(k for k in code_hashes() if (mj.get("code_sha256") or {}).get(k) != code_hashes()[k])
        raise BError("code changed since the run-in ({}): rerun the run-in in a new B root".format(changed))
    reports = {}
    for name, file_path, pattern in (("etapes_check", etapes_report, r"Result: (\d+) checks passed, 0 failed\."),
                                     ("unit_tests", tests_report, r"(?m)^OK( \(skipped=\d+\))?\s*$")):
        if not file_path or not os.path.isfile(file_path):
            raise BError("{} report missing: {}".format(name, file_path))
        with open(file_path, "rb") as handle:
            text = handle.read().decode("utf-8", "replace")
        if not re.search(pattern, text) or (name == "unit_tests" and re.search(r"(?m)^FAILED", text)):
            raise BError("{} report {} does not show a clean pass".format(name, file_path))
        reports[name] = {"path": os.path.abspath(file_path), "sha256": sha256_file(file_path)}
    reports["run_in"] = {"path": os.path.abspath(path), "sha256": sha256_file(path), "environment": env}
    return reports


def check_stats_resolution(root, plan):
    """The statistical procedure b-crossed-bootstrap-1 must be RESOLVED (tools/confirmation/stats_reference.py
    resolve) before the freeze: reproduced synthetic results with the very statistics file B uses, under Python 3.7."""
    path = os.path.join(root, "stats_resolution.json")
    if not os.path.isfile(path):
        raise BError("statistical reference not resolved: run ETAPES.cmd b-stats-results then b-stats-resolve "
                     "(no freeze with an unverified reference)")
    r = read_json(path)
    if r.get("procedure") != "b-crossed-bootstrap-1":
        raise BError("statistical procedure {!r} refused: B uses b-crossed-bootstrap-1".format(r.get("procedure")))
    res = r["results"]
    if not os.path.isfile(res["path"]) or sha256_file(res["path"]) != res["sha256"]:
        raise BError("the reference-results report changed after the resolution")
    if res["statistics_module_sha256"] != plan["statistics_module_sha256"]:
        raise BError("the resolution was made with another statistics module than the one B uses")
    if not str(res["python"]).startswith(REQUIRED_ENV["python"]):
        raise BError("the reference results were reproduced under Python {}, not {}x".format(res["python"], REQUIRED_ENV["python"]))
    return dict(r, file_sha256=sha256_file(path))


def freeze(root, a_root, aext_root, rob_root, etapes_report=None, tests_report=None, free=None):
    path = os.path.join(root, "freeze.json")
    if os.path.exists(path):
        raise BError("already frozen: {}".format(path))
    plan = build_plan(root, a_root, aext_root, rob_root)
    reports = check_freeze_prerequisites(root, etapes_report, tests_report)
    stats = check_stats_resolution(root, plan)
    need = check_disk(root, len(plan["jobs"]), plan["estimate"]["bytes_per_run"], free)
    if not os.path.isdir(root):
        os.makedirs(root)
    margins = dict((p, v) for p, v in plan["margins"].items())
