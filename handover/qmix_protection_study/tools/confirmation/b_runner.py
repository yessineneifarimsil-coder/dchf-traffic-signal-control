def check_frozen(root, plan=None):
    path = os.path.join(root, "freeze.json")
    if not os.path.isfile(path):
        raise BError("B is not frozen: run `freeze` first (nothing runs before the freeze)")
    fr = read_json(path)
    if fr["code_sha256"] != code_hashes():
        changed = sorted(k for k in fr["code_sha256"] if fr["code_sha256"][k] != code_hashes().get(k))
        raise BError("code differs from the freeze: {}".format(changed))
    if sha256_file(os.path.join(root, "margins.json")) != fr["margins_sha256"]:
        raise BError("margins.json differs from the freeze")
    if plan is not None and plan["fingerprint"] != fr["plan_fingerprint"]:
        raise BError("plan fingerprint {} differs from the frozen {}".format(plan["fingerprint"], fr["plan_fingerprint"]))
    if sha256_file(fr["statistics_module_path"]) != fr["statistics_module_sha256"]:
        raise BError("statistics module differs from the freeze")
    sp = os.path.join(root, "stats_resolution.json")
    if not os.path.isfile(sp) or sha256_file(sp) != fr["statistical_procedure"]["file_sha256"]:
        raise BError("stats_resolution.json differs from the freeze")
    return fr


