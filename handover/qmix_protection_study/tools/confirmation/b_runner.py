def free_bytes(path):
    path = os.path.abspath(path)
    while not os.path.exists(path):
        path = os.path.dirname(path)
    return shutil.disk_usage(path).free


def check_disk(root, remaining, bytes_per_run, free=None):
    need = remaining * bytes_per_run + SAFETY_BYTES
    have = free_bytes(root) if free is None else free
    if have < need:
        raise BError("not enough disk space: {:.2f} GB free, {} runs x {:.1f} MB + 4 GB = {:.2f} GB needed. "
                     "Free space first (ETAPES.cmd disk-audit; archive to another drive; deleting campaign A data is "
                     "disabled in this delivery).".format(
                         have / 1e9, remaining, bytes_per_run / 1e6, need / 1e9))
    return need


def shard(jobs, spec):
    i, n = (int(x) for x in spec.split("/"))
    if not 0 <= i < n:
        raise BError("bad shard {}".format(spec))
    return [j for pos, j in enumerate(unique_jobs(jobs)) if pos % n == i]


def run(root, shard_spec, evaluator=None, free=None):
    plan = load_plan(root)
    mine = shard(plan["jobs"], shard_spec)
    remaining = [j for j in mine if classify(root, j)[0] not in FINISHED]
    check_disk(root, len(remaining), plan["estimate"]["bytes_per_run"], free)
    evaluator = evaluator or default_evaluator
    corrupted, unfinished = [], []
    i, n = shard_spec.split("/")
    log = open(os.path.join(root, "run_log_shard{}of{}.jsonl".format(i, n)), "a")
    for j in mine:
        if SD.role_of(j["profile"], j["seed"]) != "confirmation":
            raise BError("not a confirmation seed: {}".format(j["directory"]))
        state, why = classify(root, j)
        if state in FINISHED:
            continue
        if state == "corrupted":
            print("CORRUPTED, preserved, NOT rerun: {} ({})".format(j["directory"], "; ".join(why)))
            corrupted.append(j["directory"])
            continue
        final = os.path.join(root, j["directory"])
        work = final + ".tmp"
        if state == "interrupted":
            if os.path.exists(final + ".incomplete1"):
                print("INTERRUPTED TWICE, preserved, NOT rerun: {}".format(j["directory"]))
                unfinished.append(j["directory"])
                continue
            os.rename(final if os.path.isdir(final) else work, final + ".incomplete1")
        os.makedirs(os.path.dirname(final), exist_ok=True)
        prefix = os.path.join(root, "manifests", "{}_{}".format(j["profile"], j["seed"]))
        t0 = time.time()
        try:
            evaluator(root, j, prefix, work)
            n_sched = int(read_json(prefix + ".metadata.json")["scheduled_total"])
            finalize_cell(root, j, work, final, n_sched)
        except Exception as error:  # noqa: BLE001 - technical interruption; the resume rule applies
            print("INTERRUPTED: {} ({!r})".format(j["directory"], error))
        state, why = classify(root, j)
        log.write(json.dumps({"dir": j["directory"], "state": state, "problems": why, "wall_s": time.time() - t0,
                              "t_end": time.time(), "profile": j["profile"],
                              "type": ("learned:{}:{}".format(j["method"], j["arm"]) if j["kind"] == "learned"
                                       else "comparator:" + j["spec"]["kind"])}) + "\n")
        log.flush()
        if state == "corrupted":
            corrupted.append(j["directory"])
        elif state not in FINISHED:
            unfinished.append(j["directory"])
    log.close()
    print("shard {}: {} corrupted, {} not finished".format(shard_spec, len(corrupted), len(unfinished)))
    return 5 if corrupted else (3 if unfinished else 0)


def preflight(root, free=None):
    """Before launching workers: frozen plan and code, prepared, enough disk for ALL remaining runs."""
    plan = load_plan(root)
    remaining = [j for j in plan["jobs"] if classify(root, j)[0] not in FINISHED]
    need = check_disk(root, len(remaining), plan["estimate"]["bytes_per_run"], free)
    print("preflight OK: {} runs to do, {:.2f} GB required with the 4 GB margin, plan {}".format(
        len(remaining), need / 1e9, plan["fingerprint"]))
    return 0


def progress(root):
    plan = load_plan(root)
    states = {}
    for j in plan["jobs"]:
        states.setdefault(classify(root, j)[0], []).append(j["directory"])
    total = len(plan["jobs"])
    done = sum(len(states.get(s, [])) for s in FINISHED)
    print("finished {}/{} (scientific failures {}) | corrupted {} | interrupted {} | not started {}".format(
        done, total, len(states.get("scientific_failure", [])), len(states.get("corrupted", [])),
        len(states.get("interrupted", [])), len(states.get("not_started", []))))
    for j in [j for j in plan["jobs"] if j["directory"] in set(states.get("corrupted", []))][:20]:
        why = classify(root, j)[1]
        kind = "TECHNICAL" if any(w.startswith("TECHNICAL CONTRACT") for w in why) else "CORRUPTED"
        print("  {} (preserved, not rerun): {} - {}".format(kind, j["directory"], "; ".join(why[:3])))
    if states.get("corrupted"):
        return 5
    return 0 if done == total else 3


